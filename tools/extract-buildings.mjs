// Extracts building footprints from the OpenStreetMap extracts in data/ and writes
// src/buildingData.js: one outline per building, in the map's original (unscaled)
// game-world pixels, using the same projection as the roads.
//
// Usage: node tools/extract-buildings.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapData } from '../src/mapData.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OSM_FILES = ['data/map.osm', 'data/map-south.osm'];
const SKIPPED_KINDS = new Set(['demolished', 'ruins', 'construction']);
const { bounds, world } = mapData;

function project(lat, lon) {
  return [
    ((lon - bounds.minLon) / (bounds.maxLon - bounds.minLon)) * world.width,
    ((bounds.maxLat - lat) / (bounds.maxLat - bounds.minLat)) * world.height,
  ].map((value) => Math.round(value * 10) / 10);
}

const buildings = new Map();
for (const file of OSM_FILES) {
  const xml = fs.readFileSync(path.join(root, file), 'utf8');
  const nodes = new Map();
  for (const match of xml.matchAll(/<node id="(\d+)"[^>]*lat="([-\d.]+)" lon="([-\d.]+)"/g)) {
    nodes.set(match[1], [Number(match[2]), Number(match[3])]);
  }
  for (const match of xml.matchAll(/<way id="(\d+)"[^>]*>([\s\S]*?)<\/way>/g)) {
    const kind = match[2].match(/k="building" v="([^"]+)"/)?.[1];
    if (!kind || SKIPPED_KINDS.has(kind)) continue;
    const points = [...match[2].matchAll(/<nd ref="(\d+)"/g)]
      .map((ref) => nodes.get(ref[1]))
      .filter(Boolean)
      .map(([lat, lon]) => project(lat, lon));
    // A closed outline repeats its first point at the end; drop the repeat.
    if (points.length < 4) continue;
    const inside = points.some(([x, y]) => x >= 0 && y >= 0 && x <= world.width && y <= world.height);
    if (!inside) continue;
    // The extracts overlap; keep whichever copy of a way has the most nodes.
    if (points.length > (buildings.get(match[1])?.points.length ?? 0)) {
      buildings.set(match[1], { kind, points: points.slice(0, -1) });
    }
  }
}

const output = `// Generated by tools/extract-buildings.mjs from the OpenStreetMap extracts in data/.
// © OpenStreetMap contributors, licensed under the ODbL. Don't hand-edit; re-run the tool.
// Original (unscaled) map coordinates. kind is the OSM building tag (house, shed, ...).
export const BUILDINGS = ${JSON.stringify([...buildings.values()])};
`;
fs.writeFileSync(path.join(root, 'src/buildingData.js'), output);
console.log(`Wrote ${buildings.size} buildings to src/buildingData.js`);
