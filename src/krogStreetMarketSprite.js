export function createKrogStreetMarketSprite() {
  const sprite = document.createElement('canvas');
  sprite.width = KROG_STREET_MARKET_ROWS[0].length;
  sprite.height = KROG_STREET_MARKET_ROWS.length;
  const spriteContext = sprite.getContext('2d');

  KROG_STREET_MARKET_ROWS.forEach((row, y) => {
    [...row].forEach((pixel, x) => {
      const color = KROG_STREET_MARKET_PALETTE[pixel];
      if (!color) return;
      spriteContext.fillStyle = color;
      spriteContext.fillRect(x, y, 1, 1);
    });
  });

  return sprite;
}
